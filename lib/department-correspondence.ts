import {
  CorrespondenceType,
  DocumentEventType,
  DocumentProcessingStatus,
  MalwareScanStatus,
  SignatureProfileStatus,
  type User,
} from "@/lib/generated/prisma/client";
import { db } from "@/lib/db";
import { departmentIdentity } from "@/lib/department-secretaries";
import { storeSystemGeneratedPdf } from "@/lib/document-storage";
import { itfLogoPng } from "@/lib/itf-branding";
import { renderOutgoingLetter } from "@/lib/outgoing-letter-output";
import { richTextPlainText } from "@/lib/rich-text";

type DepartmentUser = Pick<User, "department" | "workspaceDepartmentId">;

export async function activeDepartmentCorrespondenceProfile(user: DepartmentUser) {
  const identity = departmentIdentity(user);
  if (!identity) throw new Error("Your synchronized staff profile does not identify a department.");
  const profile = await db.departmentCorrespondenceProfile.findUnique({ where: { departmentKey: identity.key } });
  if (!profile?.isActive) {
    throw new Error(`The system administrator must configure the outgoing-letter profile for ${identity.name} before a letter can be submitted.`);
  }
  return { identity, profile };
}

export async function regenerateWorkingOutgoingLetter(correspondenceId: string, options: { replaceAnnotated?: boolean } = {}) {
  const record = await db.correspondence.findUnique({
    where: { id: correspondenceId },
    include: {
      departmentCorrespondenceProfile: true,
      attachments: { where: { isIncluded: true }, orderBy: { createdAt: "asc" } },
    },
  });
  if (
    !record ||
    record.type !== CorrespondenceType.OUTGOING_LETTER ||
    !record.departmentCorrespondenceProfile ||
    !record.ultimateRecipientName ||
    !record.ultimateRecipientEmail ||
    !record.ultimateRecipientAddress ||
    !richTextPlainText(record.body)
  ) return { status: "not-applicable" as const };

  const current = record.attachments.find((item) => item.isOutgoingLetterPreview);
  if (current) {
    const annotation = await db.documentAnnotation.findFirst({
      where: { OR: [{ sourceAttachmentId: current.id }, { outputAttachmentId: current.id }] },
      select: { id: true },
    });
    if (annotation && !options.replaceAnnotated) return { status: "annotated" as const, attachmentId: current.id };
  }

  const plan = record.sendingDepartmentKey
    ? await db.directorateContinuityPlan.findFirst({
        where: { departmentKey: record.sendingDepartmentKey, isActive: true },
        include: { director: true },
      })
    : null;
  const generatedAt = new Date();
  const bytes = await renderOutgoingLetter({
    referenceNumber: record.referenceNumber,
    classification: record.classification,
    subject: record.subject,
    body: record.body,
    summary: record.summary,
    letterDate: record.dateOnDocument ?? record.receivedAt,
    departmentName: record.sendingDepartmentName ?? record.departmentCorrespondenceProfile.departmentName,
    departmentEmail: record.sendingDepartmentEmail ?? record.departmentCorrespondenceProfile.emailAddress,
    addressLines: record.sendingDepartmentAddressLines.length ? record.sendingDepartmentAddressLines : record.departmentCorrespondenceProfile.addressLines,
    recipient: {
      name: record.ultimateRecipientName,
      organization: record.ultimateRecipientOrganization,
      email: record.ultimateRecipientEmail,
      address: record.ultimateRecipientAddress,
    },
    director: plan ? { name: plan.director.name } : null,
    generatedAt,
    logoPng: await itfLogoPng(),
    draftPreview: true,
  });
  const safeReference = record.referenceNumber.replace(/[^a-zA-Z0-9._-]/g, "-");
  const stored = await storeSystemGeneratedPdf({
    correspondenceId: record.id,
    recordFileId: record.recordFileId,
    originalName: `${safeReference}-outgoing-letter-working-preview.pdf`,
    bytes,
  });
  const attachment = await db.$transaction(async (tx) => {
    if (current) {
      const replaced = await tx.attachment.updateMany({
        where: { id: current.id, isIncluded: true, sha256: current.sha256 },
        data: { isIncluded: false },
      });
      if (replaced.count !== 1) throw new Error("The outgoing-letter preview changed while it was being refreshed.");
    }
    return tx.attachment.create({
      data: {
        correspondenceId: record.id,
        ...stored,
        isOutgoingLetterPreview: true,
        processingStatus: DocumentProcessingStatus.AVAILABLE,
        malwareScanStatus: MalwareScanStatus.BYPASSED,
        detectedMimeType: "application/pdf",
        processedAt: generatedAt,
        documentEvents: { create: {
          type: DocumentEventType.RELEASED,
          detail: "Generated by ITF Flow as the departmental outgoing-letter working preview.",
          metadata: { template: "ITF_DEPARTMENT_LETTERHEAD_V1", departmentProfileVersion: record.departmentCorrespondenceProfileVersion },
        } },
      },
    });
  });
  return { status: "generated" as const, attachmentId: attachment.id };
}

export async function activeDirectorSignature(departmentKey: string) {
  const plan = await db.directorateContinuityPlan.findFirst({
    where: { departmentKey, isActive: true },
    include: {
      director: {
        include: {
          signatureProfiles: {
            where: { status: SignatureProfileStatus.APPROVED },
            orderBy: { version: "desc" },
            take: 1,
          },
        },
      },
    },
  });
  if (!plan) throw new Error("Configure the department's Director and next-in-line continuity plan before finalizing an outgoing letter.");
  const signature = plan.director.signatureProfiles[0];
  if (!signature) throw new Error(`${plan.director.name} must add an active transparent PNG signature profile before an outgoing letter can be finalized.`);
  return { plan, director: plan.director, signature };
}
